// UI language. Chinese source strings are the keys; English comes from EN. Library content is
// never translated here. The choice is 'system' (default), 'zh' or 'en'; changing it reloads the
// page so strings built at module load follow too.
const KEY = 'memex.m.lang';
export const langPref = () => localStorage.getItem(KEY) || 'system';
export const uiLang = (() => {
  const pref = langPref();
  if (pref === 'zh' || pref === 'en') return pref;
  return /^zh\b/i.test(navigator.language || '') ? 'zh' : 'en';
})();
document.documentElement.lang = uiLang === 'en' ? 'en' : 'zh-CN';
export function setLangPref(value) {
  if (value === 'system') localStorage.removeItem(KEY); else localStorage.setItem(KEY, value);
  location.reload();
}

export function tx(zh, ...args) {
  const text = uiLang === 'en' ? (EN[zh] ?? zh) : (ZH[zh] ?? zh);
  return args.length ? text.replace(/\{(\d+)\}/g, (_, i) => String(args[Number(i)])) : text;
}

