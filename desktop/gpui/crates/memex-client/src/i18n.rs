//! Interface language, matching the phone web app and the Chrome extension:
//! the Chinese source string is the key, `EN` maps it to English, and a missing
//! entry falls back to the Chinese key. The current language is process-global so
//! every module reads the same choice; views translate when they render, so a
//! switch shows on the next frame.

use serde::{Deserialize, Deserializer, Serialize};
use std::{
    collections::HashMap,
    fmt::Display,
    sync::{
        atomic::{AtomicU8, Ordering},
        OnceLock,
    },
};

/// Resolved interface language.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Lang {
    Zh,
    En,
}

/// Stored preference: `system | zh | en`. Missing or unknown values mean `system`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum LanguagePref {
    #[default]
    System,
    Zh,
    En,
}

impl<'de> Deserialize<'de> for LanguagePref {
    fn deserialize<D: Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
        // Never fail a settings file over this field: anything else is `system`.
        Ok(match serde_json::Value::deserialize(d)?.as_str() {
            Some("zh") => LanguagePref::Zh,
            Some("en") => LanguagePref::En,
            _ => LanguagePref::System,
        })
    }
}

impl LanguagePref {
    pub const ALL: [LanguagePref; 3] = [LanguagePref::System, LanguagePref::Zh, LanguagePref::En];

    pub fn resolve(self, system: Lang) -> Lang {
        match self {
            LanguagePref::System => system,
            LanguagePref::Zh => Lang::Zh,
            LanguagePref::En => Lang::En,
        }
    }

    /// Language names stay in their own language, as on the other surfaces.
    pub fn label(self) -> &'static str {
        match self {
            LanguagePref::System => tx("跟随系统"),
            LanguagePref::Zh => "中文",
            LanguagePref::En => "English",
        }
    }
}

/// A BCP 47 tag such as `zh-Hans-CN` or `en-US`: `zh*` is Chinese, anything else English.
pub fn lang_from_tag(tag: &str) -> Lang {
    if tag.trim().to_ascii_lowercase().starts_with("zh") { Lang::Zh } else { Lang::En }
}

static CURRENT: AtomicU8 = AtomicU8::new(0);

pub fn set_language(lang: Lang) {
    CURRENT.store(if lang == Lang::En { 1 } else { 0 }, Ordering::SeqCst);
}

pub fn language() -> Lang {
    if CURRENT.load(Ordering::SeqCst) == 1 { Lang::En } else { Lang::Zh }
}

fn table() -> &'static HashMap<&'static str, &'static str> {
    static T: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    T.get_or_init(|| EN.iter().copied().collect())
}

fn reverse() -> &'static HashMap<&'static str, &'static str> {
    static T: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    T.get_or_init(|| EN.iter().map(|(k, v)| (*v, *k)).collect())
}

/// `key` in `lang`; Chinese, or a key without an English entry, returns the key.
pub fn tx_in(lang: Lang, key: &'static str) -> &'static str {
    match lang {
        // Keep existing translation keys/API terminology; Chinese calls a Group a 库.
        Lang::Zh => match key {
            "分组" => "分库",
            "新建分组" => "新建库",
            "还没有分组" => "还没有库",
            "当前代理未提供分组" => "当前服务未提供分库",
            "分组名称" => "库名称",
            "加入分组…" => "加入库…",
            "加入分组" => "加入库",
            "分组已在别处变化，已刷新，请再试一次" => "库已在别处变化，已刷新，请再试一次",
            "分组修改结果未知：{0}。再次提交会重试同一请求，不会重复写入。" => "库修改结果未知：{0}。再次提交会重试同一请求，不会重复写入。",
            _ => key,
        },
        Lang::En => table().get(key).copied().unwrap_or(key),
    }
}

/// `key` in the current interface language.
pub fn tx(key: &'static str) -> &'static str {
    tx_in(language(), key)
}

/// Translates `key`, then fills positional `{0}`, `{1}`… with `args`.
pub fn txf(key: &'static str, args: &[&dyn Display]) -> String {
    fill(tx(key), args)
}

fn fill(template: &str, args: &[&dyn Display]) -> String {
    let mut out = template.to_string();
    for (i, a) in args.iter().enumerate() {
        out = out.replace(&format!("{{{i}}}"), &a.to_string());
    }
    out
}

/// A fixed UI string stored before a language switch (a notice, a status), shown
/// in the current language. Either language's form is recognised; anything else,
/// including formatted text, is returned unchanged.
pub fn relabel(stored: &str) -> String {
    let key = table().get_key_value(stored).map(|(k, _)| *k).or_else(|| reverse().get(stored).copied());
    match key {
        Some(k) => tx(k).to_string(),
        None => stored.to_string(),
    }
}

